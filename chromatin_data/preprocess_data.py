import subprocess
from glob import glob
from pathlib import Path

def preprocess_data(bwa_path = None, samtools_path = None, fasta = 'GCF_003668045.3_CriGri-PICRH-1.0_genomic.fna', macs_path = None):
    # Downloading / extracting the reference PICRH genome if needed
    if not glob(fasta) and not glob(f'{fasta}.gz'):
        subprocess.run(['wget', 'https://ftp.ncbi.nlm.nih.gov/genomes/all/GCF/003/668/045/GCF_003668045.3_CriGri-PICRH-1.0/GCF_003668045.3_CriGri-PICRH-1.0_genomic.fna.gz']) # Untested but should work
    if not glob(fasta) and glob(f'{fasta}.gz'): # .gz compressed file is available, but the regular fasta is not
        if 'gzip' not in locals(): import gzip
        if 'shutil' not in locals(): import shutil
        # Extracting the fasta file from the .gz file - from https://stackoverflow.com/questions/31028815/how-to-unzip-gz-file-using-python
        with gzip.open(f'{fasta}.gz', 'rb') as f_gzip:
            with open(fasta, 'wb') as f_out:
                shutil.copyfileobj(f_gzip, f_out)
    # Attempting to find the path to bwa and samtools automatically if the user did not pass it manually
    if bwa_path is None:
        bwa_path = _get_path('bwa')
    if samtools_path is None:
        samtools_path = _get_path('samtools')
    # Generating the index of the reference genome for BWA
    if not glob(f'{fasta}.bwt'):
        print('***preprocess_data.py: Generating index for the reference genome (via "bwa index fasta")')
        subprocess.run([bwa_path, 'index', fasta])
    for bam_file in glob('*Input*[!r][p,1][0-9].bam'): # Only the controls. See below for the comments on the other regex
        _preprocess_bam(bam_file, bwa_path, samtools_path, fasta)
    for bam_file in glob('*[!r][p,1][0-9].bam'): # [0-9] to avoid finding the _aligned.bam, _sorted.bam, or _sorted-unique.bam files that are generated by this step. [!r] to avoid finding the "{histone_type}_Tp{time_point}_chr{chr_number}.bam" files, and [p,1] to avoid specifically the *_chr10.bam file
        # Pre-setup for running MACS
        chromatin_modification = bam_file.split('_Tp')[0].split('_')[-1]
        timepoint = int(bam_file.split('_Tp')[-1][:-4])
        if 'Input' in bam_file or glob(f'{chromatin_modification}_Tp{timepoint:02}_peaks.narrowPeak'): # These either are the controls, so we do not need to run callpeaks on them (as controls were handled earlier above) or these files have already been preprocessed
            continue
        _preprocess_bam(bam_file, bwa_path, samtools_path, fasta)
        # Setting a control file. The logic is that we will use the file closest to the timepoint, with ties going to the earlier control
        if timepoint <= 7:
            control_file = 'BSF_0116_C55NLACXX_2_Library_E_1_4_Input_5_Tp5_sorted-unique-chr.bam'
        elif timepoint <= 11:
            control_file = 'BSF_0116_C55NLACXX_2_Library_E_1_11_Input_9_Tp9_sorted-unique-chr.bam'
        elif timepoint <= 15:
            control_file = 'BSF_0128_C5HP5ACXX_5_Library_E_1_18_Input_13_Tp13_sorted-unique-chr.bam'
        else:
            control_file = 'BSF_0128_C5HP5ACXX_6_Library_E_1_25_Input_17_Tp17_sorted-unique-chr.bam'
        # Running MACS callpeak with default settings
        if macs_path is None:
            macs_path = _get_path('macs3')
        subprocess.run([macs_path, 'callpeak', '-t', f'{bam_file[:-4]}_sorted-unique-chr.bam', '-c', control_file, '-n', f'{chromatin_modification}_Tp{timepoint:02}'])
        # We need only the .narrowPeak file, which has very similar contents to the .xls file
        Path(f'{chromatin_modification}_Tp{timepoint:02}_model.r').unlink()
        Path(f'{chromatin_modification}_Tp{timepoint:02}_peaks.xls').unlink()
        Path(f'{chromatin_modification}_Tp{timepoint:02}_summits.bed').unlink()
        if glob(f'{bam_file[:-4]}_sorted-unique-chr.bam'):
            Path(f'{bam_file[:-4]}_sorted-unique-chr.bam').unlink()
    print()


def _get_path(program_name):
    """
    Attempts to find the path of 'program_name' in the $PATH.
    Automatically called by preprocess_data() and should not be called by the user.
    """
    which_program = subprocess.run(['which', program_name], capture_output = True)
    program_path = which_program.stdout.decode()[:-1] # The path to the program if it is in the $PATH. [:-1] to remove a \n at the end
    if not program_path:
        raise ValueError(f'The path to {program_name} must be passed manually (via the {program_name}_path input variable) or it must be in your $PATH.\n' +
                        'An attempt to find it in your $PATH returned:\n'+
                        which_program.stderr.decode()[:-1])
    return program_path

def _preprocess_bam(bam_file, bwa_path, samtools_path, fasta):
    """
    Runs multiple steps to preprocess a .bam file into something usable for MACS
    Automatically called by preprocess_data() and should not be called by the user.
    """
    chromatin_modification = bam_file.split('_Tp')[0].split('_')[-1]
    timepoint = int(bam_file.split('_Tp')[-1][:-4])
    # Aligning in single end mode to the Chinese Hamster reference sequence with bwa mem
    if not glob(f'{bam_file[:-4]}_aligned.sam') and not glob(f'{bam_file[:-4]}_aligned.bam') and not glob(f'{bam_file[:-4]}_sorted.bam') and not glob(f'{bam_file[:-4]}_sorted-unique.bam') and not glob(f'{bam_file[:-4]}_sorted-unique-chr.bam') and not glob(f'{chromatin_modification}_Tp{timepoint:02}_peaks.narrowPeak'):
        print(f'***preprocess_data.py: Aligning file {bam_file}')
        # First, convert a .bam file to .fastq via samtools. Then, pipe that .fastq file to bwa for alignment. This saves disk space and may save time. From https://www.biostars.org/p/134638/
        subprocess.run([f'{samtools_path} fastq {bam_file} | {bwa_path} mem {fasta} - -t 16 > {bam_file[:-4]}_aligned.sam'], shell = True) # TODO: get number of threads automatically or allow user to input it
    # Removing the raw .bam file
    if glob(bam_file):
        Path(bam_file).unlink()
    # Converting the aligned .sam file to .bam
    if glob(f'{bam_file[:-4]}_aligned.sam') and not glob(f'{bam_file[:-4]}_aligned.bam'):
        print(f'***preprocess_data.py: Converting file {bam_file[:-4]}_aligned.sam to a .bam file')
        subprocess.run([samtools_path, 'view', '-h', '-b', f'{bam_file[:-4]}_aligned.sam', '-o', f'{bam_file[:-4]}_aligned.bam'])
    # Removing the .sam file
    if glob(f'{bam_file[:-4]}_aligned.sam'):
        Path(f'{bam_file[:-4]}_aligned.sam').unlink()
    # Sorting the aligned .bam file
    if glob(f'{bam_file[:-4]}_aligned.bam') and not glob(f'{bam_file[:-4]}_sorted.bam'):
        print(f'***preprocess_data.py: Sorting the {bam_file[:-4]}_aligned.bam file')
        subprocess.run([samtools_path, 'sort', f'{bam_file[:-4]}_aligned.bam', '-o', f'{bam_file[:-4]}_sorted.bam'])
    # Removing the aligned .bam file
    if glob(f'{bam_file[:-4]}_aligned.bam'):
        Path(f'{bam_file[:-4]}_aligned.bam').unlink()
    # Obtaining only unique mapped readings from the sorted .bam file
    if glob(f'{bam_file[:-4]}_sorted.bam') and not glob(f'{bam_file[:-4]}_sorted-unique.bam'):
        print(f'***preprocess_data.py: Obtaining unique mapped readings from the {bam_file[:-4]}_sorted.bam file')
        subprocess.run([samtools_path, 'view', '-F', '4', '-q', '1', f'{bam_file[:-4]}_sorted.bam', '-o', f'{bam_file[:-4]}_sorted-unique.bam']) # -F 4 = removes all entries with the 4 flag (unmapped entries); -q 1 = takes only the entries with q >= 1 (unique entries). From https://www.biostars.org/p/56246/
    # Removing the sorted .bam file
    if glob(f'{bam_file[:-4]}_sorted.bam'):
        Path(f'{bam_file[:-4]}_sorted.bam').unlink()
    # Removing the unmatched fragments from the _sorted-unique.bam file
    if glob(f'{bam_file[:-4]}_sorted-unique.bam') and not glob(f'{bam_file[:-4]}_sorted-unique-chr.bam'):
        print(f'***preprocess_data.py: Removing unmatched fragments from the {bam_file[:-4]}_sorted-unique.bam file')
        if not glob(f'{bam_file[:-4]}_sorted-unique.bam.bai'):
            subprocess.run([samtools_path, 'index', f'{bam_file[:-4]}_sorted-unique.bam'])
        chr_accession = ['NW_023276806.1', 'NW_023276807.1', 'NC_048595.1', 'NC_048596.1', 'NC_048597.1', 'NC_048598.1', 'NC_048599.1', 'NC_048600.1', 'NC_048601.1', 'NC_048602.1', 'NC_048603.1', 'NC_048604.1'] # First two are for chr1, others are for chr2--10 and chrX
        subprocess.run([samtools_path, 'view', f'{bam_file[:-4]}_sorted-unique.bam'] + chr_accession + ['-o', f'{bam_file[:-4]}_sorted-unique-chr.bam'])
    # Removing the sorted and unique .bam file
    if glob(f'{bam_file[:-4]}_sorted-unique.bam'):
        Path(f'{bam_file[:-4]}_sorted-unique.bam').unlink()

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description = 'Preprocesses the BAM files from CHO-Epigenome to obtain the chromatin modifications over time.')
    parser.add_argument('-bwa', '--bwa_path', type = str, nargs = 1, metavar = '~/bwa/bwa', default = [None], help = 'Path to the bwa file. This argument can be ignored if bwa is in your $PATH.')
    parser.add_argument('-st', '-samtools', '--samtools_path', type = str, nargs = 1, metavar = '~/samtools-1.20/samtools', default = [None], help = 'Path to the samtools file. This argument can be ignored if samtools is in your $PATH.')
    parser.add_argument('--fasta', type = str, nargs = 1, metavar = 'GCF_003668045.3_CriGri-PICRH-1.0_genomic.fna', default = ['GCF_003668045.3_CriGri-PICRH-1.0_genomic.fna'], help = 'Name of the .fasta file containing the reference sequence. Should be left as "GCF_003668045.3_CriGri-PICRH-1.0_genomic.fna" unless one is reusing this script for another organism/alignment.')
    parser.add_argument('-m', '-macs', '--macs_path', type = str, nargs = 1, metavar = None, default = [None], help = 'Path to the macs3 file. This argument can be ignored if macs3 is in your $PATH. Edit the code accordingly if using macs2.')
    args = parser.parse_args()
    preprocess_data(args.bwa_path[0], args.samtools_path[0], args.fasta[0], args.macs_path[0])
